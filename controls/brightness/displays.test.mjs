import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source = readFileSync(new URL('displays.js',import.meta.url),'utf8').replace(/^\.pragma library\s*\n/,'');
const D = new Function(source+';return {parse,rates,argv,currentMode,brightness,CONFIRM_SECONDS,COMMAND_TIMEOUT};')();
const monitor = {name:'eDP-1',width:2560,height:1600,refreshRate:180,scale:1.6,x:-1600,y:20,
    availableModes:['2560x1600@60.00Hz','2560x1600@180.00Hz','1920x1080@60.00Hz']};
assert.equal(D.CONFIRM_SECONDS,10);
assert.deepEqual(D.rates(monitor),monitor.availableModes.slice(0,2));
const command = D.argv(monitor,D.rates(monitor)[0]);
assert.deepEqual(command.slice(0,2),['hyprctl','eval']);
assert.match(command[2],/scale = 1\.6/);
assert.match(command[2],/position = "-1600x20"/);
assert.match(D.argv(monitor,D.currentMode(monitor))[2],/2560x1600@180/);
for (const bad of [{...monitor,scale:NaN},{...monitor,x:undefined},{...monitor,scale:0}]) assert.equal(D.argv(bad,D.currentMode(monitor)),null);
assert.equal(D.argv(monitor,'1920x1080@60'),null);
assert.deepEqual(D.parse('broken'),[]);
assert.equal(D.brightness('panel,backlight,50,65%,100',true),65);
assert.equal(D.brightness('45\n',false),45);
for (const value of ['', 'unavailable', '-1', '101']) assert.equal(D.brightness(value,false),null);
console.log('PASS display command safety and brightness parsing');
// Exercise the real session functions with a queued runner; no subprocesses or writes.
const qml = readFileSync(new URL('DisplaySession.qml',import.meta.url),'utf8');
const functions = qml.slice(qml.indexOf('    function refresh()'),qml.lastIndexOf('}'));
const jobs = [];
const state = {runner:{run:(key,argv,timeout,callback) => { jobs.push({key,argv,callback}); return true; }},
    jobPrefix:'test',monitors:[monitor],focused:monitor,levels:{},error:'',rollback:null,phase:'idle',remaining:0,deadline:0};
const names = [...functions.matchAll(/function (\w+)\(/g)].map(m=>m[1]);
const methods = new Function('Displays','state',`with(state) { ${functions}; return {${names.join(',')}}; }`)(D,state);
Object.assign(state,methods);
state.choose('2560x1600@60.00Hz');
assert.equal(state.phase,'reading');
const fresh = {...monitor,focused:true,scale:1.75,x:200};
jobs.shift().callback(JSON.stringify([fresh]),0,'');
assert.equal(state.phase,'applying');
const write = jobs.shift();
assert.match(write.argv[2],/scale = 1\.75/);
assert.match(write.argv[2],/position = "200x20"/);
assert.doesNotMatch(write.argv[2],/Hz/);
write.callback('ok',0,'');
assert.equal(state.phase,'confirm');
assert.equal(state.remaining,10);
state.revert();
assert.equal(state.phase,'reverting');
const revert = jobs.shift();
assert.match(revert.argv[2],/2560x1600@180/);
assert.match(revert.argv[2],/scale = 1\.75/);
revert.callback('',1,'failed');
assert.equal(state.phase,'revertFailed');
assert.ok(state.rollback);
state.revert();
jobs.shift().callback('ok',0,'');
assert.equal(state.rollback,null);
assert.equal(state.phase,'idle');
jobs.length=0;
state.choose('2560x1600@60.00Hz');
jobs.shift().callback(JSON.stringify([fresh]),0,'');
jobs.shift().callback('ok',0,'');
state.confirm();
assert.equal(state.phase,'idle');
assert.equal(state.rollback,null);
console.log('PASS display snapshot, confirm, revert and retry lifecycle');
